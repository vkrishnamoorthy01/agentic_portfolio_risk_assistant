"""Which price file /analytics reads.

Sources, named as in quant_risk_and_trading_portfolio:
  kite        Kite Connect daily closes
  ibkr_paper  IBKR daily closes through the paper account
  ibkr_live   IBKR daily closes through the live account (market data only)
  synthetic   data/mock_prices.csv, generated, not market data
  latest      (default) whichever downloaded source has the most recent
              session; synthetic only if nothing has been downloaded

Market prices are never fetched while serving a request. Kite needs a daily
login and IBKR needs TWS running, so scripts/refresh_prices.py downloads
them into data/prices_<source>.csv, with data/prices_<source>.json
describing the download. A request reads the newest file on disk, so a
refresh is picked up without restarting the service. PRICE_DATA_DIR points
at another folder for the downloads, e.g. Render's /etc/secrets where
uploaded secret files appear.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

DATA_DIR = Path(__file__).parent.parent / "data"
MARKET_SOURCES = ("kite", "ibkr_paper", "ibkr_live")
SOURCE_CHOICES = ("latest", *MARKET_SOURCES, "synthetic")
# When two downloads end on the same session, prefer the live IBKR account, then Kite, then paper.
TIE_PREFERENCE = ("ibkr_live", "kite", "ibkr_paper")
REFRESH_HINT = (
    "For newer prices, run `python scripts/refresh_prices.py --source kite|ibkr_paper|ibkr_live` "
    "(Kite needs a login; IBKR needs TWS running). Otherwise this is the latest data available."
)
SYNTHETIC_NOTE = (
    "Synthetic prices from data/mock_prices.csv (generated by data/generate_mock_data.py), "
    "not market data; as_of is the last date in that file."
)


class UnknownSourceError(ValueError):
    """A price source that does not exist, or one that has not been downloaded yet."""


def download_dir() -> Path:
    """Where downloaded prices live: PRICE_DATA_DIR if set (on Render, /etc/secrets for uploaded
    secret files), else data/. The synthetic file always stays in data/."""
    return Path(os.environ["PRICE_DATA_DIR"]) if os.environ.get("PRICE_DATA_DIR") else DATA_DIR


def snapshot_path(source: str) -> Path:
    return DATA_DIR / "mock_prices.csv" if source == "synthetic" else download_dir() / f"prices_{source}.csv"


def snapshot_meta(source: str) -> dict | None:
    """The refresh script's description of a downloaded source, or None if it has not been downloaded."""
    meta = download_dir() / f"prices_{source}.json"
    if source == "synthetic" or not meta.exists() or not snapshot_path(source).exists():
        return None
    return json.loads(meta.read_text(encoding="utf-8"))


def available_sources() -> dict[str, str]:
    """Each downloaded market source and its last session date."""
    return {s: m["last_session"] for s in MARKET_SOURCES if (m := snapshot_meta(s))}


def default_source() -> str:
    return os.environ.get("PRICE_SOURCE", "latest")


def resolve_source(requested: str | None = None) -> str:
    """The concrete source to read for a request ("latest" resolved)."""
    requested = requested or default_source()
    if requested not in SOURCE_CHOICES:
        raise UnknownSourceError(f"Unknown price source {requested!r}; use one of {list(SOURCE_CHOICES)}.")
    if requested == "latest":
        available = available_sources()
        if not available:
            return "synthetic"
        return max(available, key=lambda s: (available[s], -TIE_PREFERENCE.index(s)))
    if requested != "synthetic" and snapshot_meta(requested) is None:
        raise UnknownSourceError(
            f"No {requested} prices downloaded yet. Run `python scripts/refresh_prices.py --source {requested}`, "
            f"or use source=latest. Downloaded: {available_sources() or 'none'}."
        )
    return requested


def data_note(source: str, requested: str) -> str:
    if source == "synthetic":
        return SYNTHETIC_NOTE if requested == "synthetic" else f"{SYNTHETIC_NOTE} No market prices are downloaded. {REFRESH_HINT}"
    meta = snapshot_meta(source) or {}
    picked = "the most recent download" if requested == "latest" else "the requested source"
    return (
        f"{meta.get('description', source)}, last session {meta.get('last_session')}, "
        f"file built {meta.get('built_utc')}{' from stored bars' if meta.get('cache_only') else ''}; {picked}. "
        f"Nothing was fetched for this request. {REFRESH_HINT}"
    )
